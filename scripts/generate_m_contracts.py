#!/usr/bin/env python3
"""Generate JSON Schema and TypeScript from the same Pydantic definitions."""
import argparse
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from platform_m.contracts import MODELS
from platform_m.evidence import canonical, digest

ROOT = Path(__file__).resolve().parents[1]

def type_of(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        import json
        return json.dumps(schema['const'])
    if 'enum' in schema:
        import json
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(type_of(v) for v in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        return '('+type_of(schema.get('items', {}))+')[]'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean',
            'null': 'null', 'object': 'Record<string, unknown>'}.get(kind, 'unknown')

def generated():
    schemas = {model.__name__: model.model_json_schema() for model in MODELS}
    declarations = {}
    for name, schema in schemas.items():
        declarations.update(schema.get('$defs', {}))
        declarations[name] = schema
    lines = ['// Generated by scripts/generate_m_contracts.py; do not edit.',
             'export const schemaChecksum = "'+digest(schemas)+'";']
    for name, schema in sorted(declarations.items()):
        lines.append('export interface '+name+' {')
        for key, value in schema.get('properties', {}).items():
            optional = '' if key in schema.get('required', []) else '?'
            lines.append('  '+key+optional+': '+type_of(value)+';')
        lines.append('}')
    return {'schema.json': canonical(schemas)+b'\n', 'contracts.ts': ('\n'.join(lines)+'\n').encode(),
            'checksum.txt': (digest(schemas)+'\n').encode()}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    directory = ROOT/'packages/contracts'
    for name, data in generated().items():
        path = directory/name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit('DBG-M-002 contract drift: '+name)
        else:
            directory.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

if __name__ == '__main__':
    main()
